use crate::cli::Shell;
use anyhow::Result;
use bof2exe::manifest::Manifest;
use clap::Command;
use std::{fmt::Write as _, io::Write as _, path::Path};

fn commands(mut cmd: Command, prefix: String, out: &mut Vec<(String, Command)>) {
    cmd.build();
    out.push((prefix.clone(), cmd.clone()));
    for sub in cmd
        .get_subcommands()
        .filter(|s| !s.is_hide_set() && s.get_name() != "help")
    {
        commands(sub.clone(), format!("{prefix} {}", sub.get_name()), out);
    }
}
fn all(cmd: Command) -> Vec<(String, Command)> {
    let name = cmd.get_name().to_owned();
    let mut out = Vec::new();
    commands(cmd, name, &mut out);
    out
}
pub fn docs(cmd: Command, output: &Path) -> Result<()> {
    std::fs::create_dir_all(output)?;
    let mut markdown =
        String::from("# Command reference\n\nGenerated by `bof2exe docs` from the CLI model.\n\n");
    for (name, mut command) in all(cmd) {
        let mut help = Vec::new();
        command.write_long_help(&mut help)?;
        let help = String::from_utf8(help)?;
        writeln!(markdown, "## {name}\n\n```text\n{help}\n```\n")?;
        let filename = name.replace(' ', "-");
        let mut man = format!(
            ".TH {} 1\n.SH NAME\n{}\n.SH USAGE\n.nf\n",
            filename.to_uppercase(),
            roff(&name)
        );
        for line in help.lines() {
            writeln!(man, "{}", roff(line))?;
        }
        man.push_str(".fi\n");
        std::fs::write(output.join(format!("{filename}.1")), man)?;
    }
    std::fs::write(output.join("cli.md"), markdown)?;
    Ok(())
}
fn roff(value: &str) -> String {
    let escaped = value.replace('\\', "\\e").replace('-', "\\-");
    if escaped.starts_with(['.', '\'']) {
        format!("\\&{escaped}")
    } else {
        escaped
    }
}
fn words(command: &Command) -> Vec<String> {
    let mut out: Vec<String> = command
        .get_subcommands()
        .filter(|s| !s.is_hide_set())
        .map(|s| s.get_name().to_owned())
        .collect();
    for arg in command.get_arguments().filter(|a| !a.is_hide_set()) {
        if let Some(long) = arg.get_long() {
            out.push(format!("--{long}"));
        }
        if let Some(short) = arg.get_short() {
            out.push(format!("-{short}"));
        }
    }
    out.sort();
    out.dedup();
    out
}
pub fn completions(cmd: Command, shell: Shell) -> Result<()> {
    let table = all(cmd);
    let mut output = String::new();
    match shell {
        Shell::Bash => {
            output.push_str("# Command and option name completion, generated from clap.\n_bof2exe() {\n  local opts\n  case \"${COMP_WORDS[1]}\" in\n");
            for (name, command) in &table {
                let pattern = if name == "bof2exe" {
                    "*"
                } else {
                    name.strip_prefix("bof2exe ").unwrap_or(name)
                };
                if pattern == "*" {
                    continue;
                }
                writeln!(
                    output,
                    "    {pattern}) opts='{}' ;;",
                    words(command).join(" ")
                )?;
            }
            writeln!(output, "    *) opts='{}' ;;", words(&table[0].1).join(" "))?;
            output.push_str("  esac\n  COMPREPLY=( $(compgen -W \"$opts\" -- \"${COMP_WORDS[COMP_CWORD]}\") )\n}\ncomplete -o default -F _bof2exe bof2exe\n");
        }
        Shell::PowerShell => {
            output.push_str("# Command and option name completion, generated from clap.\nRegister-ArgumentCompleter -Native -CommandName bof2exe,bof2exe.exe -ScriptBlock {\n  param($wordToComplete, $commandAst, $cursorPosition)\n  $choices = @{\n");
            for (name, command) in &table {
                let key = name.strip_prefix("bof2exe ").unwrap_or("");
                let values = words(command)
                    .iter()
                    .map(|v| format!("'{v}'"))
                    .collect::<Vec<_>>()
                    .join(", ");
                writeln!(output, "    '{key}' = @({values})")?;
            }
            output.push_str("  }\n  $key = ''\n  if ($commandAst.CommandElements.Count -gt 1) {\n    $candidate = $commandAst.CommandElements[1].Extent.Text\n    if ($choices.ContainsKey($candidate)) { $key = $candidate }\n  }\n  $choices[$key] | Where-Object { $_.StartsWith($wordToComplete, [StringComparison]::OrdinalIgnoreCase) } | ForEach-Object {\n    [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterName', $_)\n  }\n}\n");
        }
    }
    std::io::stdout().write_all(output.as_bytes())?;
    Ok(())
}
pub fn module_docs(module: &Manifest) -> Result<()> {
    let report = bof2exe::inspect::inspect(&bof2exe::read_input(&module.object)?, &module.entry)?;
    let mut text = format!("# {}\n\n{}\n\nEntrypoint: `{}`\n\nArchitecture: `{}`\n\nSHA-256: `{}`\n\n## Default arguments\n\n```json\n{}\n```\n\n## Imports\n\n", module.name, module.description, module.entry, report.architecture, report.sha256, serde_json::to_string_pretty(&module.arguments)?);
    if report.imports.is_empty() {
        text.push_str("None.\n");
    }
    for import in &report.imports {
        writeln!(text, "- `{import}`")?;
    }
    text.push_str("\n## Compatibility\n\n");
    if report.compatible() {
        text.push_str("Static checks passed. DLL exports are resolved at load time.\n\n");
    }
    for issue in &report.issues {
        writeln!(text, "- {issue}")?;
    }
    for note in &report.notes {
        writeln!(text, "- {note}")?;
    }
    std::io::stdout().write_all(text.as_bytes())?;
    Ok(())
}

pub fn cna_docs(report: &bof2exe::cna::Report, markdown: bool) -> Result<()> {
    let mut text = String::new();
    if markdown {
        writeln!(
            text,
            "# CNA command reference\n\nSource: `{}`\n",
            report.source
        )?;
    }
    for command in &report.commands {
        if markdown {
            writeln!(text, "## {}\n", command.name)?;
        } else {
            writeln!(
                text,
                "{} ({}, line {})",
                command.name, command.kind, command.line
            )?;
        }
        if let Some(description) = &command.description {
            writeln!(text, "{description}\n")?;
        }
        if let Some(usage) = &command.usage {
            writeln!(text, "Usage: {usage}\n")?;
        }
        for (index, pack) in command.packs.iter().enumerate() {
            writeln!(
                text,
                "Variant {} at line {}: format {}\n",
                index + 1,
                pack.line,
                pack.format.as_deref().unwrap_or("<dynamic>")
            )?;
            if markdown {
                text.push_str("| Position | Wire type | CNA expression |\n| --- | --- | --- |\n");
            }
            for param in &pack.parameters {
                if markdown {
                    writeln!(
                        text,
                        "| {} | {} | `{}` |",
                        param.position,
                        param.wire_type,
                        param.expression.replace('|', "\\|").replace('\n', " ")
                    )?;
                } else {
                    writeln!(
                        text,
                        "  {}: {:<6} {}",
                        param.position, param.wire_type, param.expression
                    )?;
                }
            }
            text.push('\n');
            for diagnostic in &pack.diagnostics {
                writeln!(text, "Diagnostic: {diagnostic}\n")?;
            }
        }
        if !command.object_hints.is_empty() {
            writeln!(text, "Object hints: {}\n", command.object_hints.join(", "))?;
        }
        if !command.entrypoints.is_empty() {
            writeln!(text, "Entrypoints: {}\n", command.entrypoints.join(", "))?;
        }
        if !command.calls.is_empty() {
            writeln!(
                text,
                "Helper calls to review: {}\n",
                command.calls.join(", ")
            )?;
        }
    }
    for diagnostic in &report.diagnostics {
        writeln!(text, "Note: {diagnostic}\n")?;
    }
    std::io::stdout().write_all(text.as_bytes())?;
    Ok(())
}
